CREATE FUNCTION savia_core.capture_realtime_event() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  principal TEXT;
  topic_name TEXT;
  event_type TEXT;
  collection_name TEXT;
  resource TEXT;
  prior_status TEXT;
  current_status TEXT;
BEGIN
  IF TG_TABLE_NAME = 'assistant_threads' THEN
    IF TG_OP = 'DELETE' THEN
      principal := OLD.user_id;
      event_type := 'deleted';
      resource := OLD.id;
    ELSIF TG_OP = 'INSERT' THEN
      principal := NEW.user_id;
      event_type := 'created';
      resource := NEW.id;
    ELSE
      principal := NEW.user_id;
      event_type := 'updated';
      resource := NEW.id;
    END IF;
    topic_name := 'assistant-threads';
    collection_name := 'threads';
  ELSE
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    principal := NEW.principal_id;
    resource := NEW.id;
    topic_name := 'request-pages';
    collection_name := NEW.page_name;
    IF TG_OP = 'INSERT' THEN
      current_status := NEW.status;
      event_type := 'created';
    ELSE
      prior_status := OLD.status;
      current_status := NEW.status;
      IF current_status = prior_status THEN
        RETURN NEW;
      END IF;
      event_type := 'updated';
    END IF;
    IF current_status NOT IN ('complete', 'failed') THEN
      RETURN NEW;
    END IF;
  END IF;

  INSERT INTO savia_core.realtime_event_outbox
    (principal_id, topic, type, collection, resource_id, created_at)
  VALUES (
    principal,
    topic_name,
    event_type,
    collection_name,
    resource,
    to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;
